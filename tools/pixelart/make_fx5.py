def codefont():
    frames = []
    for ch in GLYPH_CHARS:
        img = Img(8, 8)
        rows = FONT[ch]
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == '#':
                    img.set(x + 1, y, W)        # 칸 안 1px 여백 (왼쪽) · 위는 0줄부터 7줄
        frames.append(img)
    return frames


def devcursor():
    frames = []
    shape = [
        "#...........",
        "##..........",
        "#o#.........",
        "#oo#........",
        "#ooo#.......",
        "#oooo#......",
        "#ooooo#.....",
        "#oooooo#....",
        "#ooooooo#...",
        "#oooo#####..",
        "#oo#oo#.....",
        "#o#.#oo#....",
        "##..#oo#....",
        "#....#oo#...",
        ".....####...",
    ]
    for f in range(2):
        img = Img(16, 16)
        s = 1 if f == 1 else 0
        for y, row in enumerate(shape):
            for x, c in enumerate(row):
                if s and (x >= 11 or y >= 14):
                    continue
                if c == '#':
                    img.set(x + 1 + s, y + s, K)
                elif c == 'o':
                    img.set(x + 1 + s, y + s, GOLD)
        for y in range(2, 13 - s):          # 왼쪽 가장자리 터미널 초록 한 줄
            img.set(2 + s, y + s, TERM)
        if f == 1:
            ring(img, 2.5, 1.5, 1.6, 0.9, W)
        frames.append(img)
    return frames


def codeblock():
    frames = []
    NAVY = (30, 35, 70, 255)
    for f in range(2):
        img = Img(16, 16)
        rim = GOLD if f == 0 else (255, 240, 170, 255)
        for y in range(1, 15):
            for x in range(1, 15):
                img.set(x, y, NAVY)
        for i in range(1, 15):
            img.set(i, 1, rim); img.set(i, 14, rim); img.set(1, i, rim); img.set(14, i, rim)
        for i in range(0, 16):
            img.set(i, 0, K); img.set(i, 15, K); img.set(0, i, K); img.set(15, i, K)
        # 가운데 초록 「{ }」
        for (x, y) in ((5, 5), (4, 6), (4, 7), (3, 8), (4, 9), (4, 10), (5, 11)):
            img.set(x, y - 0, TERM)
        for (x, y) in ((10, 5), (11, 6), (11, 7), (12, 8), (11, 9), (11, 10), (10, 11)):
            img.set(x, y, TERM)
