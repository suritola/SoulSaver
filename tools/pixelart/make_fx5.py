def slipper():
    img = Img(24, 16)
    PINK = (240, 140, 180, 255); DARK = (170, 80, 120, 255)
    for x in range(1, 23):
        t = (x - 1) / 21.0
        half = 3.2 + 2.6 * math.sin(t * math.pi) ** 0.7
        for y in range(16):
            if abs(y + 0.5 - 8) <= half:
                img.set(x, y, DARK if x < 6 else PINK)
    # 앞 띠 (흰색 한 줄 — 줄무늬 여러 줄 금지)
    for y in range(16):
        for x in range(13, 17):
            if img.get(x, y)[3] > 0:
                img.set(x, y, W)
    # 진한 외곽
    out = Img(24, 16)
    for y in range(16):
        for x in range(24):
            if img.get(x, y)[3] == 0:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < 24 and 0 <= ny < 16 and img.get(nx, ny)[3] > 0:
                        out.set(x, y, K)
                        break
            else:
                out.set(x, y, img.get(x, y))
    return [out]


def scratcher():
    img = Img(8, 40)
    BAM = (215, 195, 140, 255); NODE = (150, 120, 70, 255)
    for y in range(9, 39):
        img.set(3, y, BAM); img.set(4, y, BAM)
        img.set(2, y, K); img.set(5, y, K)
    for y in (16, 25, 33):
        img.set(3, y, NODE); img.set(4, y, NODE)
    img.set(3, 39, K); img.set(4, 39, K)
    # 끝의 휘어진 작은 손 (손가락 4)
    for x in range(1, 7):
        img.set(x, 8, BAM)
    for x in (1, 3, 4, 6):
        for y in range(3, 8):
            img.set(x, y, BAM)
    for x in range(0, 8):
        img.set(x, 9, K)
    for x in (0, 2, 5, 7):
        for y in range(3, 9):
            img.set(x, y, K)
    for x in (1, 3, 4, 6):
        img.set(x, 2, K)
    return [img]


def broom():
    frames = []
    STRAW = (230, 200, 110, 255); SHADE = (190, 150, 70, 255); RED = (210, 50, 60, 255)
    for f in range(2):
        img = Img(24, 16)
        lean = 2 if f == 0 else -2
        for x in range(3, 21):
            top = 4
            bot = 13 + (1 if x % 3 == 0 else 0)
            for y in range(top, bot + 1):
                xs = x + int(round(lean * (y - top) / (bot - top + 1)))
                if 0 <= xs < 24:
                    img.set(xs, y, STRAW if (x + y) % 4 else SHADE)
        for x in range(3, 21):
            img.set(x, 5, RED); img.set(x, 6, RED)
        for x in range(9, 15):              # 손잡이 끝
            for y in range(0, 4):
                img.set(x, y, (120, 80, 50, 255))
        out = Img(24, 16)
        for y in range(16):
            for x in range(24):
                if img.get(x, y)[3] == 0:
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        nx, ny = x + dx, y + dy
                        if 0 <= nx < 24 and 0 <= ny < 16 and img.get(nx, ny)[3] > 0:
                            out.set(x, y, K)
                            break
                else:
                    out.set(x, y, img.get(x, y))
        frames.append(out)
    return frames


def medal():
    frames = []
    G = (255, 210, 70, 255); GS = (190, 140, 30, 255)
    RIB_R = (215, 50, 60, 255); RIB_B = (60, 100, 220, 255)
    for f in range(2):
        img = Img(16, 20)
        # 리본 (빨강 · 파랑)
        for y in range(0, 8):
            for x in range(3 + y // 3, 7 + y // 3):
                img.set(x, y, RIB_R)
            for x in range(9 - y // 3, 13 - y // 3):
                img.set(x, y, RIB_B)
        disc(img, 8, 13, 6.2, K)
        disc(img, 8, 13, 5.2, GS)
        disc(img, 7.6, 12.6, 4.4, G)
        # 「1」
        for y in range(10, 17):
            img.set(8, y, GS); img.set(7, y, GS)
        img.set(6, 11, GS)
        for x in range(6, 10):
            img.set(x, 16, GS)
        hx, hy = (5, 10) if f == 0 else (10, 15)
        img.set(hx, hy, W); img.set(hx + 1, hy, W); img.set(hx, hy + 1, W)
        frames.append(img)
    return frames


def momeye():
    frames = []
    LID = (240, 140, 180, 255)
    for f in range(2):
        img = Img(16, 10)
        open_h = 3.2 if f == 0 else 1.4
        for y in range(10):
            for x in range(16):
                dx = (x + 0.5 - 8) / 7.0
                dy = (y + 0.5 - 5.5)
                lim = open_h * max(0.0, 1 - dx * dx)
                if abs(dy) <= lim:
                    img.set(x, y, W)
                elif abs(dy) <= lim + 1.2 and abs(dx) < 1:
                    img.set(x, y, LID if dy < 0 else K)
        disc(img, 8, 5.5, min(2.4, open_h), (60, 40, 30, 255))
        disc(img, 8, 5.5, min(1.2, open_h * 0.5), K)
        img.set(9, 4, W)
        for x in (3, 6, 10, 13):            # 속눈썹
            img.set(x, 0 if f == 0 else 2, K)
        frames.append(img)
    return frames


